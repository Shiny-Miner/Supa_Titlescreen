#define TITLE_BAND_ROW      17         // band = tile rows 17..19 (bottom 24 pixels)
#define TITLE_PROMPT_ROW    17
#define TITLE_COPY_ROW      19
#define TILE_BAND           1          // tile 0 stays blank/transparent
#define TILE_PROMPT         2
#define TILE_COPY           (TILE_PROMPT + TITLE_COLS * TITLE_PROMPT_SCALE)
#define TITLE_TEXT_PAL_BITS (TITLE_TEXT_PAL_BANK << 12)

static const u16 sTitleTextPal[16] = { 0, TITLE_BAND_COLOR, TITLE_TEXT_COLOR };

// One centred line of flat text. `yOff` is in font rows (before scaling).
static void DrawTitleLine(const char *str, u32 scale, u32 yOff, u32 firstTile)
{
    u32 rows = 8 * scale;
    u8 *buf = AllocZeroed(240 * rows);

    if (buf == NULL)
        return;
    BlitText(buf, rows, str, scale, yOff * scale, 2, 2, 0);
    BufToTiles(buf, scale, (vu32 *)TITLE_TEXT_TILES, firstTile, 1);   // background = band colour
    Free(buf);
}

static void LoadTitleText(void)
{
    vu16 *map = (vu16 *)TITLE_TEXT_MAP;
    vu32 *band = (vu32 *)(TITLE_TEXT_TILES + TILE_BAND * 32);
    u32 r, c;

    for (c = 0; c < 8; c++)
        band[c] = 0x11111111;           // solid band colour (palette index 1)

    LoadPalette(sTitleTextPal, TITLE_TEXT_PAL_BANK * 16, 0x20);
    DrawTitleLine(TITLE_PROMPT_TEXT, TITLE_PROMPT_SCALE, 1, TILE_PROMPT);
    DrawTitleLine(TITLE_COPYRIGHT_TEXT, 1, 0, TILE_COPY);

    for (r = TITLE_BAND_ROW; r < TITLE_BAND_ROW + 3; r++)
        for (c = 0; c < TITLE_COLS; c++)
            map[r * 32 + c] = TILE_BAND | TITLE_TEXT_PAL_BITS;

    for (r = 0; r < TITLE_PROMPT_SCALE; r++)
        for (c = 0; c < TITLE_COLS; c++)
            map[(TITLE_PROMPT_ROW + r) * 32 + c] = (TILE_PROMPT + r * TITLE_COLS + c) | TITLE_TEXT_PAL_BITS;

    for (c = 0; c < TITLE_COLS; c++)
        map[TITLE_COPY_ROW * 32 + c] = (TILE_COPY + c) | TITLE_TEXT_PAL_BITS;
}

// Blinking = swapping the prompt's tilemap entries between its text tiles and the
// blank band tile. Cheap, and independent of the palette fade.
static void SetPromptVisible(bool8 on)
{
    vu16 *map = (vu16 *)TITLE_TEXT_MAP;
    u32 r, c;

    if (map[TITLE_PROMPT_ROW * 32] == (on ? (TILE_PROMPT | TITLE_TEXT_PAL_BITS) : (TILE_BAND | TITLE_TEXT_PAL_BITS)))
        return;     // already in that state

    for (r = 0; r < TITLE_PROMPT_SCALE; r++)
        for (c = 0; c < TITLE_COLS; c++)
            map[(TITLE_PROMPT_ROW + r) * 32 + c] =
                (on ? (TILE_PROMPT + r * TITLE_COLS + c) : TILE_BAND) | TITLE_TEXT_PAL_BITS;
}

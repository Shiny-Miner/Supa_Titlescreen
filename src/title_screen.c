static void CreateTitleMon(void)
{
    u8 id;
    struct Sprite *sprite;

    LZDecompressVram(gMonFrontPicTable[TITLE_MON_SPECIES].data, (void *)TITLE_MON_TILES_VRAM);
    LoadCompressedPalette(gMonPaletteTable[TITLE_MON_SPECIES].data, 0x100, 0x20);  // OBJ palette 0

#if TITLE_MON_SHADOW
    {
        vu32 *dst = (vu32 *)(TITLE_MON_TILES_VRAM + 64 * 32);
        u32 i;

        for (i = 0; i < 8 * 8; i++)
            dst[i] = sTitleShadowTiles[i];
        LoadPalette(sTitleShadowPal, 0x110, 0x20);                                 // OBJ palette 1
        // Only the 2nd-target layers are set. A semi-transparent OBJ (the shadow) blends by
        // itself; setting OBJ as a 1st target here would make EVERY sprite translucent.
        SetGpuReg(REG_OFFSET_BLDCNT, BLDCNT_TGT2_BG0 | BLDCNT_TGT2_BD);
        SetGpuReg(REG_OFFSET_BLDALPHA, BLDALPHA_BLEND(7, 9));
        CreateSprite(&sTitleShadowTemplate, TITLE_MON_X, TITLE_MON_Y + TITLE_MON_SHADOW_DY, 1);
    }
#endif

    id = CreateSprite(&sTitleMonTemplate, TITLE_MON_X, TITLE_MON_Y, 0);
    if (id >= MAX_SPRITES)
        return;

    sprite = &gSprites[id];
    InitSpriteAffineAnim(sprite);       // makes sure the sprite owns an OAM matrix
    sprite->affineAnimPaused = TRUE;    // we drive the matrix ourselves, not the anim table
    SetTitleMonMatrix(sprite->oam.matrixNum, 0x40, 0x40, 0);   // start small, like the first frame of the grow-in
}


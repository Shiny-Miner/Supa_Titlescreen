#define TITLE_COLS          30
#define TITLE_FONT_ADVANCE  6          // pixels per character at 1x

// BEGIN_TEXT_ENGINE (extracted by a host test harness; keep free of game calls)
static u32 NextGlyph(const u8 **p)
{
    u32 c = *(*p)++;

    // 2-byte UTF-8 (covers the (c) sign and e-acute); anything else is Latin-1.
    if (c >= 0xC2 && c < 0xE0 && (**p & 0xC0) == 0x80)
        c = ((c & 0x1F) << 6) | (*(*p)++ & 0x3F);

    if (c >= 32 && c <= 126)
        return c - 32;
    if (c == 0xA9)
        return TITLE_GLYPH_COPYRIGHT;
    if (c == 0xE9)
        return TITLE_GLYPH_EACUTE;
    return '?' - 32;
}

static u32 CountGlyphs(const char *str)
{
    const u8 *p = (const u8 *)str;
    u32 n = 0;

    while (*p)
    {
        NextGlyph(&p);
        n++;
    }
    return n;
}

// Draws `str` centred into buf (240 pixels wide, `rows` tall), `scale` times larger, with
// its top at pixel row y0. Glyph pixels in the upper rows get `top`, the rest `bottom`
// (equal values = flat colour, different = a two-tone gradient). `spacing` adds extra
// pixels (before scaling) between characters. Other pixels are untouched.
static void BlitText(u8 *buf, u32 rows, const char *str, u32 scale, u32 y0, u8 top, u8 bottom, u32 spacing)
{
    const u8 *p = (const u8 *)str;
    u32 count = CountGlyphs(str);
    u32 advance = TITLE_FONT_ADVANCE + spacing;
    u32 width = count * advance * scale;
    u32 x0 = width < 240 ? (240 - width) / 2 : 0;
    u32 i = 0, gx, gy, sx, sy;

    while (*p)
    {
        const u8 *g = sTitleFont[NextGlyph(&p)];

        for (gy = 0; gy < 8; gy++)
        {
            for (gx = 0; gx < 8; gx++)
            {
                if (!(g[gy] & (0x80 >> gx)))
                    continue;
                for (sy = 0; sy < scale; sy++)
                {
                    for (sx = 0; sx < scale; sx++)
                    {
                        u32 px = x0 + (i * advance + gx) * scale + sx;
                        u32 py = y0 + gy * scale + sy;

                        if (px < 240 && py < rows)
                            buf[py * 240 + px] = gy < 3 ? top : bottom;
                    }
                }
            }
        }
        i++;
    }
}

// Sets every empty pixel within `radius` of a text pixel (value >= 2) to 1, for rows r0..r1-1.
static void OutlineBuf(u8 *buf, u32 rows, u32 r0, u32 r1, u32 radius)
{
    s32 rad = radius;
    u32 x, y;

    for (y = r0; y < r1 && y < rows; y++)
    {
        for (x = 0; x < 240; x++)
        {
            s32 dx, dy;
            bool8 hit = FALSE;

            if (buf[y * 240 + x] != 0)
                continue;
            for (dy = -rad; dy <= rad && !hit; dy++)
            {
                for (dx = -rad; dx <= rad; dx++)
                {
                    s32 nx = (s32)x + dx, ny = (s32)y + dy;

                    if (nx >= 0 && nx < 240 && ny >= 0 && ny < (s32)rows && buf[ny * 240 + nx] >= 2)
                    {
                        hit = TRUE;
                        break;
                    }
                }
            }
            if (hit)
                buf[y * 240 + x] = 1;
        }
    }
}

// Packs buf into 4bpp tiles: `tileRows` rows of 30 tiles starting at tile `firstTile` of the
// charblock at `base`. Empty pixels (0) become `bgValue`.
static void BufToTiles(const u8 *buf, u32 tileRows, vu32 *base, u32 firstTile, u32 bgValue)
{
    u32 tx, ty, x, y;

    for (ty = 0; ty < tileRows; ty++)
    {
        for (tx = 0; tx < TITLE_COLS; tx++)
        {
            vu32 *tile = base + (firstTile + ty * TITLE_COLS + tx) * 8;

            for (y = 0; y < 8; y++)
            {
                u32 word = 0;

                for (x = 0; x < 8; x++)
                {
                    u32 c = buf[(ty * 8 + y) * 240 + tx * 8 + x];

                    word |= (c ? c : bgValue) << (x * 4);
                }
                tile[y] = word;
            }
        }
    }
}
